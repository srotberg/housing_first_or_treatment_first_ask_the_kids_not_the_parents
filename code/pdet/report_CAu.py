# report_CAu.py <tf dir> <null dir> -- the long-run CA arm at detection 1.00 against the corrected Housing First
# (16 October; the author: "do one run in which pdet is say 100% and those with SUD cannot get a voucher at all. That may
# raise homelessness"). Each dir holds final.txt and cf.log.gz (or cf.log). Prints the drug price, pi_V, and the changes
# in drug use, SUD, homelessness h_1 and children in a shelter: the homelessness of households aged 26-50 (the years a
# child is at home), mass-weighted, from the arm's last DIAG age lines, as paper/transition_series.py's steady() does.
import gzip, os, re, sys


def final(d):
    out = {}
    for l in open(os.path.join(d, 'final.txt')):
        m = re.match(r'\s+(.+?)\s{2,}([-+0-9.Ee]+)(\s|$)', l)
        if m:
            out[m.group(1).strip()] = float(m.group(2))
    return out


def child_hl(d):
    p = os.path.join(d, 'cf.log.gz')
    f = gzip.open(p, 'rt', errors='replace') if os.path.exists(p) else open(os.path.join(d, 'cf.log'), errors='replace')
    rows = {}
    for l in f:
        m = re.search(r'DIAG age\s+(\d+)\s+homeless=\s*(\S+).*sud=\s*(\S+)\s+mass=\s*(\S+)', l)
        if m:
            rows[int(m.group(1))] = (float(m.group(2)), float(m.group(4)))
    P = [a for a in rows if 26 <= a <= 50]
    assert len(P) == 25, f'{d}: DIAG age lines for {len(P)} of the 25 ages 26-50'
    W = sum(rows[a][1] for a in P)
    return sum(rows[a][0] * rows[a][1] for a in P) / W


tf, hf = sys.argv[1], sys.argv[2]
x, y = final(tf), final(hf)
x['children in a shelter (26-50)'], y['children in a shelter (26-50)'] = child_hl(tf), child_hl(hf)
print(f'# Treatment First, rule CA (the disorder fails the screen in treatment or not, any use fails), detection 1.00,')
print(f'# against the corrected Housing First ({hf}); generated by code/pdet/report_CAu.py')
print(f"{'':34s} {'Treatment First':>16s} {'Housing First':>14s} {'change':>9s}")
for k in ('drug price', 'pi_V (voucher probability)', 'drug use b', 'SUD lambda_d', 'homelessness h_1',
          'children in a shelter (26-50)', 'share of households holding a voucher', 'treatment take-up',
          'net government revenue', 'welfare (with childhood)'):
    if k in x and k in y:
        print(f'{k:34s} {x[k]:16.8g} {y[k]:14.8g} {100 * (x[k] / y[k] - 1):+8.2f}%')
