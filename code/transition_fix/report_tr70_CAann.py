# report_tr70_CAann.py <run.log[.gz]> <null arm dir> <tf arm dir> <curve> -- report_tr50_CA.py for the announced reform
# (remote_tr70_CAann.sh, 19 October): the same report over the first 25 years rather than 15, since the phased rule
# changes in year 6; the detection rate and the mode in the first line read from DETECTION (default 1.00) and RUN_LABEL. A COPY; report_tr50_CA.py, which the running no-escape transitions call, untouched. Its header follows.
# report_tr50_CA.py <run.log[.gz]> <null arm dir> <tf arm dir> <curve> -- THE AUTHOR'S QUESTION ON THE RULE-CA TRANSITION
# (16 October: "do one run in which pdet is say 100% and those with SUD cannot get a voucher at all. That may raise
# homelessness, and we should check also the transition for this case to show when there is a trade off").
# From the latest complete forward pass of the log (the one ending at its last 'TRANSITION PATHS SAVED'): homelessness
# h_1 and children in a shelter, year by year for the first 15 years and at the peak, against the corrected Housing
# First the path starts from, and the CEV of the cohort born at the reform (transition_fix/cohort_cev.py on that pass,
# completed with the terminal arm). Children in a shelter is paper/transition_series.py's child_hl: the homelessness of
# households aged 26-50, mass-weighted (HOMELESS_BY_AGE on the scale that reproduces h_1); the steady state's from its
# last DIAG age lines, as transition_series.py's steady().
import gzip, os, re, subprocess, sys, tempfile

log, null_dir, tf_dir, curve = sys.argv[1:5]
op = (lambda p: gzip.open(p, 'rt', errors='replace')) if log.endswith('.gz') else (lambda p: open(p, errors='replace'))
L = op(log).read().splitlines()
marks = [i for i, l in enumerate(L) if 'TRANSITION INIT PARENT SHARE RESTORED' in l]
saved = [i for i, l in enumerate(L) if 'TRANSITION PATHS SAVED after loop' in l]
assert marks and saved, 'no complete forward pass in the log'
end = saved[-1]
start = max(i for i in marks if i < end)
nxt = [i for i in marks if i > end]
cut = L[:nxt[0]] if nxt else L                        # the log up to that pass, for cohort_cev.py
loop = int(re.search(r'after loop\s+(\d+)', L[end]).group(1))
P = L[start:end + 1]


def tnum(l):
    return int(re.search(r't=\s*(\d+)', l).group(1))


def vec(l):
    f = l.split('t=')[1].split()
    return int(f[0]), [float(x) for x in f[1:]]


MECH, HB, MB, CEV = {}, {}, {}, {}
for l in P:
    if ' TRANSITION MECH t=' in l:
        MECH[tnum(l)] = {k: float(v) for k, v in re.findall(r'(\w+)=\s*([-+0-9.Ee]+)', l.split('t=', 1)[1].split(None, 1)[1])}
    elif l.startswith(' TRANSITION HOMELESS_BY_AGE t='):
        t, v = vec(l); HB[t] = v
    elif l.startswith(' TRANSITION MASS_BY_AGE t='):
        t, v = vec(l); MB[t] = v
    elif 'TRANSITION CEV t=' in l and 'CEV=' in l:
        CEV[tnum(l)] = float(l.split('CEV=')[1].split()[0])
T = sorted(MECH)


def child_hl(t):
    h = MECH[t]['h_1']; hb, mb = HB[t], MB[t]
    for raw, tol in (([x * 1e-14 for x in hb], 1e-6), ([x * m for x, m in zip(hb, mb)], 5e-4)):
        if abs(sum(raw) / sum(mb) / h - 1) < tol:
            hs = [r / m if m > 0 else 0.0 for r, m in zip(raw, mb)]
            w = mb[:25]
            return sum(hs[a] * w[a] for a in range(25)) / sum(w)
    raise SystemExit(f'HOMELESS_BY_AGE t={t} reproduces h_1 on neither scale')


def steady(d):
    rows, h1 = {}, None
    for l in gzip.open(os.path.join(d, 'cf.log.gz'), 'rt', errors='replace'):
        m = re.search(r'DIAG age\s+(\d+)\s+homeless=\s*(\S+).*sud=\s*(\S+)\s+mass=\s*(\S+)', l)
        if m:
            rows[int(m.group(1))] = (float(m.group(2)), float(m.group(4)))
    for l in open(os.path.join(d, 'final.txt')):
        m = re.match(r'\s+homelessness h_1\s+([-+0-9.Ee]+)', l)
        if m:
            h1 = float(m.group(1))
    A = [a for a in rows if 26 <= a <= 50]
    assert len(A) == 25 and h1, f'{d}: {len(A)} DIAG ages, h_1 {h1}'
    W = sum(rows[a][1] for a in A)
    return h1, sum(rows[a][0] * rows[a][1] for a in A) / W


h0, c0 = steady(null_dir)
hT, cT = steady(tf_dir)
rows = [(t, MECH[t]['h_1'], child_hl(t)) for t in T]
pct = lambda x, y: 100 * (x / y - 1)
print(f'# rule-CA transition, {os.environ.get("RUN_LABEL", "announce")}, at detection {os.environ.get("DETECTION", "1.00")}, binary loop {loop}: the forward pass ending at log line {end + 1}, '
      f'periods {T[0]}-{T[-1]}; generated by code/transition_fix/report_tr70_CAann.py')
print(f'# Housing First (start, {null_dir}): h_1 {h0:.6f}, children in a shelter {c0:.6f}; '
      f'Treatment First long run (terminal, {tf_dir}): h_1 {hT:.6f} ({pct(hT, h0):+.2f}%), '
      f'children in a shelter {cT:.6f} ({pct(cT, c0):+.2f}%)')
print(f"  {'year':>4s} {'h_1':>10s} {'vs HF':>8s} {'children in a shelter':>22s} {'vs HF':>8s}")
for t, h, c in rows[:25]:
    print(f'  {t:4d} {h:10.6f} {pct(h, h0):+7.2f}% {c:22.6f} {pct(c, c0):+7.2f}%')
th, hh, _ = max(rows, key=lambda r: r[1])
tc, _, cc = max(rows, key=lambda r: r[2])
for name, t, x, x0 in (('homelessness h_1', th, hh, h0), ('children in a shelter', tc, cc, c0)):
    word = 'RISES above' if x > x0 else 'never rises above'
    print(f'  PEAK {name}: year {t}, {x:.6f}, {pct(x, x0):+.2f}% against Housing First -- the path {word} Housing First'
          + ('' if x > x0 else ' (the peak is the highest year on the path)'))
up = [t for t, h, c in rows if h > h0 or c > c0]
print(f"  years with h_1 or children in a shelter above Housing First: {', '.join(map(str, up)) if up else 'none'}")

with tempfile.NamedTemporaryFile('w', suffix='.log', delete=False) as f:
    f.write('\n'.join(cut) + '\n'); tmp = f.name
r = subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cohort_cev.py'), tmp, curve,
                    '--terminal', os.path.join(tf_dir, 'cf.log.gz'),
                    '--refs', os.path.join(null_dir, 'cf.log.gz'), os.path.join(tf_dir, 'cf.log.gz')],
                   capture_output=True, text=True)
os.unlink(tmp)
m = re.search(r'THE COHORT BORN AT THE REFORM \(b = 1\): CEV\s+(\S+)', r.stdout)
pas = re.search(r'forward pass (\d+) of (\d+)', r.stdout)
print(f"  CEV OF THE COHORT BORN AT THE REFORM (cohort_cev.py, pass {pas.group(1) if pas else '?'}, completed with the terminal "
      f"arm): {m.group(1) if m else 'NOT COMPUTED: ' + (r.stderr or r.stdout).strip().splitlines()[-1]} of consumption")
if 1 in CEV:
    print(f'  (the model\'s own TRANSITION CEV at t = 1, the cohort entering adulthood at the reform: {100 * CEV[1]:+.3f}%)')
